const axeTags = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']

async function audit(page, screen) {
  await page.evaluate(async () => {
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
    const transitions = document.getAnimations().filter(animation => animation.effect.getComputedTiming().endTime <= 1000)
    await Promise.allSettled(transitions.map(animation => animation.finished))
  })
  const result = await new AxeBuilder({ page }).withTags(axeTags).analyze()
  expect(result.violations.map(violation => ({
    id: violation.id, nodes: violation.nodes.map(node => ({ target: node.target, issue: node.failureSummary })),
  })), screen).toEqual([])
}

